// --- helpers -----------------------------------------------------------------

// mockHandler is a tiny dispatcher keyed by "METHOD PATH". The empty
// pattern falls through to a 500. Each handler may capture request
// metadata (e.g. Idempotency-Key) for assertions.
type mockHandler struct {
	mu     sync.Mutex
	routes map[string]http.HandlerFunc
}

func newMockHandler() *mockHandler {
	return &mockHandler{routes: map[string]http.HandlerFunc{}}
}

func (m *mockHandler) on(method, path string, fn http.HandlerFunc) {
	m.mu.Lock()
	defer m.mu.Unlock()
	m.routes[method+" "+path] = fn
}

func (m *mockHandler) ServeHTTP(w http.ResponseWriter, r *http.Request) {
	m.mu.Lock()
	fn, ok := m.routes[r.Method+" "+r.URL.Path]
	m.mu.Unlock()
	if !ok {
		http.Error(w, "no route: "+r.Method+" "+r.URL.Path, http.StatusNotFound)
		return
	}
	fn(w, r)
}

func writeJSON(t *testing.T, w http.ResponseWriter, status int, body any) {
	t.Helper()
	w.Header().Set("Content-Type", "application/json")
	w.WriteHeader(status)
	if err := json.NewEncoder(w).Encode(body); err != nil {
		t.Fatalf("encode: %v", err)
	}
}

func writeProblem(t *testing.T, w http.ResponseWriter, status int, typeURI, title, detail string) {
	t.Helper()
	w.Header().Set("Content-Type", "application/problem+json")
	w.WriteHeader(status)
	_ = json.NewEncoder(w).Encode(map[string]any{
		"type":   typeURI,
		"title":  title,
		"detail": detail,
		"status": status,
	})
}

