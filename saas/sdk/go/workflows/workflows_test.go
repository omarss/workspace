func TestIdempotencyKey_AutoGeneratedAndUnique(t *testing.T) {
	var seen sync.Map
	h := newMockHandler()
	h.on("POST", "/v1/tenants", func(w http.ResponseWriter, r *http.Request) {
		key := r.Header.Get("Idempotency-Key")
		if !strings.HasPrefix(key, "idem_") {
			t.Errorf("idempotency key %q lacks idem_ prefix", key)
		}
		if _, dup := seen.LoadOrStore(key, true); dup {
			t.Errorf("duplicate idempotency key emitted: %q", key)
		}
		writeJSON(t, w, http.StatusCreated, map[string]any{
			"data": map[string]any{
				"id": "tenant_01H000000000000000000000", "slug": "acme", "name": "Acme",
				"object": "tenant", "status": "active",
				"created_at": time.Now(), "updated_at": time.Now(), "etag": `W/"v1"`,
			},
		})
	})
	srv := httptest.NewServer(h)
	defer srv.Close()
	c := newDataPlaneClient(t, srv)

	for i := 0; i < 3; i++ {
		if _, err := CreateTenant(context.Background(), c, CreateTenantInput{Slug: "acme", Name: "Acme"}); err != nil {
			t.Fatalf("iter %d: %v", i, err)
		}
	}
}

